// Deterministic edge adapter for sql.js 1.16.0's self-contained asm build.
// No runtime compiler, Wasm fetch, host filesystem, or eval is used.
import {readFileSync,writeFileSync,mkdirSync} from 'node:fs';
const source=readFileSync(new URL('../node_modules/sql.js/dist/sql-asm.js',import.meta.url),'utf8');
const environment='var aa=!!globalThis.window,ba=!!globalThis.WorkerGlobalScope,ca=globalThis.process?.versions?.node&&globalThis.process?.type!="renderer";';
if(!source.includes(environment))throw new Error('sql.js environment wrapper changed. Review the edge adapter.');
let adapted=source.replace(environment,'var aa=false,ba=false,ca=false;').replace('        module = undefined;','        var module = undefined;');
const tail=adapted.indexOf('// This bit below is copied almost exactly');
if(tail<0)throw new Error('sql.js export wrapper changed.');
adapted=adapted.slice(0,tail).replace(/\bmodule\b/g,'edgeModule').replaceAll('require("node:fs")','{}').replaceAll('require("node:crypto")','{randomFillSync:b=>crypto.getRandomValues(b)}');
adapted='// sql.js 1.16.0, MIT licensed. See sql-engine.LICENSE. Generated by scripts/prepare-sql-engine.mjs.\n'+adapted+'\nexport default initSqlJs;\n';
mkdirSync(new URL('../vendor/',import.meta.url),{recursive:true});
writeFileSync(new URL('../vendor/sql-engine.mjs',import.meta.url),adapted);
writeFileSync(new URL('../vendor/sql-engine.LICENSE',import.meta.url),readFileSync(new URL('../node_modules/sql.js/LICENSE',import.meta.url)));
